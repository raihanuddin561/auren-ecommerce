export type OrderChannelId = 'web' | 'manual' | 'facebook' | 'instagram' | 'whatsapp' | 'store';

export interface PlaceOrderCommand {
  /** Generated by the caller so the tracking token can be derived before the insert. */
  orderId: string;
  /** Where the order came from. Staff typing in a phone order use the channel of the conversation. */
  channel?: OrderChannelId;
  /** The staff member (staff_members.id) who typed the order in; null for a web order. */
  createdBy?: string | null;
  userId: string | null;
  contact: { name: string; phone: string; email: string | null };
  address: ShippingAddressSnapshot;
  addressHash: string;
  ipHash: string | null;
  customerNote: string | null;
  /** Prices and costs read from the database inside this transaction (INV-M3, INV-O5). */
  lines: ReadonlyArray<{ variant: SellableVariant; quantity: number }>;
  currency: string;
  delivery: { zoneId: string; zoneName: string; option: DeliveryOption };
  providerId: PaymentProviderId;
  plan: PlacementPlan;
  risk: { score: number; flags: string[] };
  discountMinor?: bigint;
  discountCodes?: string[];
  lineDiscounts?: ReadonlyMap<string, bigint>;
}

export interface OrderTotals {
  subtotal: Money;
  discount: Money;
  shipping: Money;
  total: Money;
}

/** Subtotal, delivery and total from database prices; the one place order arithmetic happens. */
export function totalsFor(
  lines: ReadonlyArray<{
    variant: Pick<SellableVariant, 'priceMinor' | 'currency'>;
    quantity: number;
  }>,
  currency: string,
  shipping: Money,
  discount: Money = zero(currency),
): OrderTotals {
  const subtotal = sum(
    lines.map((line) =>
      multiply(money(line.variant.priceMinor, line.variant.currency), line.quantity),
    ),
    currency,
  );
  const effectiveDiscount = discount.minor > subtotal.minor ? subtotal : discount;
  const total = add(subtract(subtotal, effectiveDiscount), shipping);
  return { subtotal, discount: effectiveDiscount, shipping, total };
}

/**
 * Writes a new order, in the caller's transaction (checkout owns the transaction, the idempotency
 * claim and the cart). In order: stock leaves through the inventory service (the atomic
 * conditional update that makes overselling impossible, INV-S2), the order and its lines are
 * written with price AND cost snapshots (INV-O5), then the timeline row, the payment record and the
 * outbox event. The order is born `placed` and waits for a staff member to verify it: nothing here
 * can confirm, and nothing ever cancels it (ADR-015, INV-O1, INV-O2).
 */
export async function createPlaced(tx: Tx, cmd: PlaceOrderCommand): Promise<PlacedOrder> {
  const discount = money(cmd.discountMinor ?? 0n, cmd.currency);
  const totals = totalsFor(cmd.lines, cmd.currency, cmd.delivery.option.charge, discount);

  let effectTags: string[] = [];
  if (cmd.plan.stock === 'commit_on_place') {
    const effect = await inventory.sell(tx, {
      referenceType: 'order',
      referenceId: cmd.orderId,
      lines: cmd.lines.map((line) => ({ variantId: line.variant.id, quantity: line.quantity })),
    });
    effectTags = effect.tags;
  } else {
    const effect = await inventory.reserve(tx, {
      referenceType: 'order',
      referenceId: cmd.orderId,
      lines: cmd.lines.map((line) => ({ variantId: line.variant.id, quantity: line.quantity })),
    });
    effectTags = effect.tags;
  }

  const option = cmd.delivery.option;
  const method: ShippingMethodSnapshot = {
    zoneId: cmd.delivery.zoneId,
    zoneName: cmd.delivery.zoneName,
    rateId: option.rateId,
    rateName: option.name,
    listedMinor: option.listed.minor.toString(),
    chargedMinor: option.charge.minor.toString(),
    freeOverMinor: option.freeOver ? option.freeOver.minor.toString() : null,
    free: option.free,
    minDays: option.minDays,
    maxDays: option.maxDays,
  };

  const created = await repo.insertOrder(tx, {
    id: cmd.orderId,
    userId: cmd.userId,
    email: cmd.contact.email,
    phone: cmd.contact.phone,
    customerName: cmd.contact.name,
    status: 'placed',
    paymentStatus: cmd.plan.orderPaymentStatus,
    fulfillmentStatus: 'unfulfilled',
    channel: cmd.channel ?? 'web',
    createdBy: cmd.createdBy ?? null,
    currency: cmd.currency,
    subtotalMinor: totals.subtotal.minor,
    discountMinor: totals.discount.minor,
    shippingChargedMinor: totals.shipping.minor,
    taxMinor: 0n,
    totalMinor: totals.total.minor,
    shippingAddress: cmd.address as unknown as Prisma.InputJsonValue,
    shippingMethod: method as unknown as Prisma.InputJsonValue,
    discountCodes: cmd.discountCodes ?? [],
    customerNote: cmd.customerNote,
    riskScore: cmd.risk.score,
    riskFlags: cmd.risk.flags,
    trackingTokenHash: hashTrackingToken(deriveTrackingToken(cmd.orderId)),
    addressHash: cmd.addressHash,
    ipHash: cmd.ipHash,
  });

  await repo.insertItems(
    tx,
    cmd.lines.map(({ variant, quantity }) => {
      const unit = money(variant.priceMinor, variant.currency);
      const lineSubtotal = multiply(unit, quantity).minor;
      const lineDiscount = cmd.lineDiscounts?.get(variant.id) ?? 0n;
      const totalMinor = lineSubtotal - lineDiscount;
      return {
        orderId: cmd.orderId,
        variantId: variant.id,
        productId: variant.productId,
        titleSnapshot: variant.productTitle,
        variantTitleSnapshot: variant.optionsLabel,
        skuSnapshot: variant.sku,
        optionsSnapshot: variant.options as unknown as Prisma.InputJsonValue,
        imageSnapshot: variant.image?.url ?? null,
        unitPriceMinor: unit.minor,
        compareAtMinor: variant.compareAtMinor,
        unitCostMinor: variant.avgCostMinor,
        quantity,
        discountMinor: lineDiscount,
        taxMinor: 0n,
        totalMinor: totalMinor < 0n ? 0n : totalMinor,
      };
    }),
  );

  await repo.insertEvent(tx, {
    orderId: cmd.orderId,
    type: 'placed',
    toStatus: 'placed',
    actorId: cmd.createdBy ?? null,
    payload: {
      channel: cmd.channel ?? 'web',
      paymentMethod: cmd.providerId,
      itemCount: cmd.lines.length,
    },
  });
  await recordPayment(tx, {
    orderId: cmd.orderId,
    providerId: cmd.providerId,
    plan: cmd.plan,
    amount: totals.total,
  });
  await enqueueEvent(tx, {
    type: 'order.placed',
    aggregateType: 'order',
    aggregateId: cmd.orderId,
    payload: {
      orderId: cmd.orderId,
      paymentMethod: cmd.providerId,
      currency: cmd.currency,
      totalMinor: totals.total.minor.toString(),
      channel: cmd.channel ?? 'web',
    },
  });

  return { orderId: cmd.orderId, orderNumber: created.orderNumber, tags: effectTags };
}

