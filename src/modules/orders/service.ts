type OrderWithDetail = NonNullable<Awaited<ReturnType<typeof repo.findById>>>;

const PAYMENT_STATUS_VIEW = [
  'unpaid',
  'pending',
  'paid',
  'partially_refunded',
  'refunded',
  'failed',
] as const;

const absoluteImage = (url: string | null): string | null => {
  if (!url) return null;
  return /^https?:\/\//.test(url) ? url : `${env.APP_URL.replace(/\/$/, '')}${url}`;
};

function paymentLabel(order: OrderWithDetail): string {
  const provider = order.payments[0]?.provider;
  if (!provider) return 'Payment';
  try {
    return getPaymentProvider(provider).label;
  } catch {
    return 'Payment';
  }
}

function addressLines(address: ShippingAddressSnapshot): string[] {
  return [
    address.line1,
    address.line2,
    [address.area, address.thana.name].filter(Boolean).join(', '),
    [address.district.name, address.division.name, address.postalCode].filter(Boolean).join(', '),
  ].filter((line): line is string => Boolean(line && line.trim()));
}

export function toCustomerView(order: OrderWithDetail): CustomerOrderView {
  const address = order.shippingAddress as unknown as ShippingAddressSnapshot;
  const method = order.shippingMethod as unknown as ShippingMethodSnapshot;
  const status = order.status as OrderStatus;
  const payment = order.paymentStatus;
  return {
    orderNumber: order.orderNumber,
    firstName: order.customerName.split(' ')[0] || order.customerName,
    status,
    statusLabel: STATUS_LABEL[status],
    timeline: timelineFor(status),
    placedAt: order.placedAt.toISOString(),
    items: order.items.map((item) => ({
      title: item.titleSnapshot,
      variantLabel: item.variantTitleSnapshot,
      quantity: item.quantity,
      unitPrice: serialize(money(item.unitPriceMinor, order.currency)),
      lineTotal: serialize(money(item.totalMinor, order.currency)),
      imageUrl: item.imageSnapshot,
    })),
    subtotal: serialize(money(order.subtotalMinor, order.currency)),
    discount: serialize(money(order.discountMinor, order.currency)),
    shipping: serialize(money(order.shippingChargedMinor, order.currency)),
    total: serialize(money(order.totalMinor, order.currency)),
    address: { name: address.fullName, lines: addressLines(address) },
    delivery: {
      zoneName: method.zoneName,
      rateName: method.rateName,
      eta: formatEta(method.minDays, method.maxDays),
    },
    payment: {
      label: paymentLabel(order),
      status: PAYMENT_STATUS_VIEW.includes(payment) ? payment : 'unpaid',
    },
    emailMasked: order.email ? maskEmail(order.email) : null,
    parcel: null,
    updates: [],
    returns: [],
    returnOffer: null,
  };
}

/** The order page view with the parcel, the dated steps and the return offer filled in. */
async function withExtras(order: OrderWithDetail): Promise<CustomerOrderView> {
  const view = toCustomerView(order);
  const extras = await loadCustomerExtras(order.id, order.status as OrderStatus, order.deliveredAt);
  return { ...view, ...extras };
}

export function toMinimalView(order: OrderWithDetail): MinimalOrderView {
  const status = order.status as OrderStatus;
  return {
    orderNumber: order.orderNumber,
    status,
    statusLabel: STATUS_LABEL[status],
    timeline: timelineFor(status),
    placedAt: order.placedAt.toISOString(),
  };
}

/** The order a tracking token belongs to, or null. The stored value is compared in constant time. */
async function orderForToken(token: string): Promise<OrderWithDetail | null> {
  if (!isTrackingToken(token)) return null;
  const hash = hashTrackingToken(token);
  const order = await repo.findByTrackingHash(db, hash);
  return order && safeEqual(order.trackingTokenHash, hash) ? order : null;
}

export async function orderIdForToken(token: string): Promise<string | null> {
  return (await orderForToken(token))?.id ?? null;
}

/**
 * The full order for a tracking token, when `unlocked` says this visitor already showed the second
 * factor (a valid proof cookie). Returns null for an unknown token and also when not unlocked
 * (the page then asks for the phone or email, the same for both cases).
 */
export async function viewForToken(
  token: string,
  isUnlocked: (orderId: string) => boolean,
): Promise<CustomerOrderView | null> {
  const order = await orderForToken(token);
  if (!order || !isUnlocked(order.id)) return null;
  return withExtras(order);
}

/**
 * Checks the phone or email a customer typed against the order behind a tracking token. Returns the
 * order id on a match and null on anything else (unknown token, wrong factor, malformed factor):
 * the caller shows one generic message for all of them.
 */
export async function verifyTokenFactor(token: string, factorText: string): Promise<string | null> {
  const factor = normalizeFactor(factorText);
  const order = await orderForToken(token);
  // Always compare, so a wrong token costs about as much as a wrong factor.
  const probe = { phone: order?.phone ?? '+8800000000000', email: order?.email ?? null };
  const matches = factor ? factorMatches(factor, probe) : false;
  return order && matches ? order.id : null;
}

/** Order number plus phone or email: the status only, never items or address (INV-O10). */
export async function lookupMinimal(
  orderNumber: string,
  factorText: string,
): Promise<MinimalOrderView | null> {
  const factor = normalizeFactor(factorText);
  const order = await repo.findByNumber(db, orderNumber.trim().toUpperCase());
  const probe = { phone: order?.phone ?? '+8800000000000', email: order?.email ?? null };
  const matches = factor ? factorMatches(factor, probe) : false;
  return order && matches ? toMinimalView(order) : null;
}

/** The order the buyer just placed, for the confirmation page of the browser that placed it. */
export async function customerViewById(orderId: string): Promise<CustomerOrderView | null> {
  const order = await repo.findById(db, orderId);
  return order ? withExtras(order) : null;
}

