const RECEIVED_TEMPLATE = 'order_received';

/**
 * Sends the "we have your order" email once. Runs in a background job after the order committed
 * (INV-E1). A retried job finds the send log and does nothing (INV-E2); an order without an email
 * address is skipped and logged as such.
 */
export async function sendOrderReceivedEmail(orderId: string): Promise<'sent' | 'skipped'> {
  const order = await repo.findById(db, orderId);
  if (!order) throw new DomainError('NOT_FOUND', 'Order not found');
  if (await wasSent(RECEIVED_TEMPLATE, 'order', orderId)) return 'skipped';
  if (!order.email) {
    await recordSend({
      channel: 'email',
      template: RECEIVED_TEMPLATE,
      toMasked: 'no email given',
      status: 'skipped',
      relatedType: 'order',
      relatedId: orderId,
    });
    return 'skipped';
  }

  const view = toCustomerView(order);
  const origin = env.APP_URL.replace(/\/$/, '');
  const rendered = await renderOrderReceivedEmail({
    firstName: view.firstName,
    orderNumber: view.orderNumber,
    lines: view.items.map((item) => ({
      title: item.title,
      variantLabel: item.variantLabel,
      quantity: item.quantity,
      unitPrice: formatPriceText(money(BigInt(item.unitPrice.minor), item.unitPrice.currency)),
      lineTotal: formatPriceText(money(BigInt(item.lineTotal.minor), item.lineTotal.currency)),
      imageUrl: absoluteImage(item.imageUrl),
    })),
    subtotal: formatPriceText(money(BigInt(view.subtotal.minor), view.subtotal.currency)),
    shipping:
      BigInt(view.shipping.minor) === 0n
        ? 'Complimentary'
        : formatPriceText(money(BigInt(view.shipping.minor), view.shipping.currency)),
    total: formatPriceText(money(BigInt(view.total.minor), view.total.currency)),
    addressLines: [view.address.name, ...view.address.lines],
    paymentLabel: view.payment.label,
    trackUrl: `${origin}/track/${deriveTrackingToken(orderId)}`,
  });

  try {
    await sendEmail({ to: order.email, ...rendered });
  } catch (error) {
    await recordSend({
      channel: 'email',
      template: RECEIVED_TEMPLATE,
      toMasked: maskEmail(order.email),
      status: 'failed',
      error: error instanceof Error ? error.message : 'send failed',
      relatedType: 'order',
      relatedId: orderId,
    });
    logger.error({ err: error, orderId }, 'order received email failed');
    // Re-thrown so the job retries; the log keeps every failed attempt.
    throw error;
  }
  await recordSend({
    channel: 'email',
    template: RECEIVED_TEMPLATE,
    toMasked: maskEmail(order.email),
    status: 'sent',
    relatedType: 'order',
    relatedId: orderId,
  });
  return 'sent';
}
